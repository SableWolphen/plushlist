const assert=require('node:assert/strict');
const React=require(process.cwd()+'/node_modules/react');
const TestRenderer=require(process.cwd()+'/node_modules/react-test-renderer');
global.React=React;global.window=new EventTarget();window.PlushLifeThemeCopy=require("../assets/plush-theme-copy.js");global.document=new EventTarget();
const esbuild=require(process.cwd()+'/node_modules/esbuild');
const os=require('node:os');
const path=require('node:path');
const fs=require('node:fs');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'plush-cozy-test-'));
const compiled=path.join(temp,'components.cjs');
esbuild.buildSync({entryPoints:['src/components/cozy-space.jsx'],bundle:true,platform:'node',format:'cjs',outfile:compiled});
const {CozySpace,CozySharing,CozyComfortContext,useCozyComfort}=require(compiled);
const {act}=TestRenderer;
const wait=()=>new Promise(resolve=>setImmediate(resolve));
let writes=[],fail=false,exposed;
const client={from(table){let op='read',payload;const q={select(){return q},eq(){return q},maybeSingle(){return q},single(){return q},upsert(value){op='write';payload=value;return q},then(resolve,reject){let result;if(op==='write'){writes.push({table,payload});result={data:payload,error:fail?new Error('offline'):null};}else result={data:table==='cozy_profiles'?{profile:{fields:{comfort_item:'Blanket',please_dont:'No calls'},memories:[{id:'win',text:'Started today',date:'2026-09-30'}]}}:[],error:null};return Promise.resolve(result).then(resolve,reject);}};return q;}};
function Harness({id='owner'}){const cozy=useCozyComfort({id},client);exposed=cozy;return React.createElement(CozyComfortContext.Provider,{value:cozy},React.createElement(CozySpace,{rows:[{key:'water',label:'Water'}],soundscapes:[],onSupport(){}}),React.createElement(CozySharing,{links:[{id:'link',owner_user_id:id,active:true,accepted_at:'date',label:'Guardian',caregiver_email:'support@example.invalid'}]}));}
(async()=>{
let tree;
await act(async()=>{tree=TestRenderer.create(React.createElement(Harness));await wait();});
assert.equal(exposed.status,'ready');
assert.equal(exposed.profile.fields.comfort_item,'Blanket');
await act(async()=>{await exposed.publish({id:'link',owner_user_id:'owner'},['comfort_item'],['win']);});
assert.deepEqual(writes.at(-1).payload.card.fields,{comfort_item:'Blanket'});
assert.deepEqual(writes.at(-1).payload.card.memories.map(m=>m.id),['win']);
assert.ok(!JSON.stringify(writes.at(-1).payload.card).includes('No calls'));
await act(async()=>{await exposed.publish({id:'link',owner_user_id:'owner'},[],[],false);});
assert.equal(writes.at(-1).payload.active,false);
assert.deepEqual(writes.at(-1).payload.card,{fields:{},memories:[]});
fail=true;
await act(async()=>{const result=await exposed.save({fields:{comfort_item:'Changed'}});assert.equal(result,false);});
assert.equal(exposed.profile.fields.comfort_item,'Blanket');
assert.match(exposed.message,/Couldn’t save/);
fail=false;
const open=tree.root.findAllByType('button').find(b=>b.children.join('')==='Open');
await act(async()=>{open.props.onClick();});
assert.equal(tree.root.findAllByType('textarea').length,0,'Landing shows choices rather than a form');
const choices=tree.root.findByProps({'aria-label':'Cozy Space choices'});
assert.equal(choices.findAllByType('button').length,3);
await act(async()=>{choices.findAllByType('button')[0].props.onClick();});
const field=tree.root.findAllByType('textarea').find(t=>t.props.value==='Blanket');
assert.ok(field,'Saved profile appears in editor');
await act(async()=>{field.props.onChange({target:{value:'My plush'}});});
const save=tree.root.findAllByType('button').find(b=>b.children.join('')==='Save my comforts');
await act(async()=>{await save.props.onClick();});
assert.equal(writes.at(-1).payload.profile.fields.comfort_item,'My plush');
const back=()=>tree.root.findAllByType('button').find(b=>b.children.join('')==='← My Cozy Space');
await act(async()=>{back().props.onClick();});
assert.equal(tree.root.findAllByType('textarea').length,0);
await act(async()=>{tree.root.findByProps({'aria-label':'Cozy Space choices'}).findAllByType('button')[1].props.onClick();});
assert.equal(tree.root.findAllByType('textarea').length,0,'Reset does not render profile or memory forms');
assert.ok(tree.root.findAllByType('button').some(b=>b.children.join('')==='Start my saved reset'));
await act(async()=>{tree.unmount();});
console.log('Cozy component interactions passed: load, edit/save, failure retention, selective publishing, and pause.');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>fs.rmSync(temp,{recursive:true,force:true}));
