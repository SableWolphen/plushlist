import assert from "node:assert/strict";
import { CARE_ROUTINES, careWords, careChecksForToday } from "../src/guardian-care.mjs";
import { freshGuardianState, normalizeGuardianState } from "../src/plush-guardian-model.mjs";
const initial = freshGuardianState();
assert.equal(initial.prefs.careMode, false);
assert.equal(initial.prefs.littleMode, false);
assert.equal(CARE_ROUTINES.length, 4);
assert(CARE_ROUTINES.every(r=>r.steps.length > 0));
assert.match(careWords({ careStyle:"baby", petName:"Pup" }),/Pup/);
assert.match(careWords({ careStyle:"structured" },"done"),/complete/);
const normalized = normalizeGuardianState({ prefs:{ careMode:true, littleMode:true, careStyle:"baby", petName:"Pup" }, careChecks:{ date:"2026-10-14", items:{"wake:0":true,"night:3":true,"not allowed":true} } });
assert.equal(normalized.prefs.careMode,true);
const withStickers = normalizeGuardianState({careStickers:["2026-10-14:wake","2026-10-14:wake","invalid"]});
assert.deepEqual(withStickers.careStickers,["2026-10-14:wake"]);
const badClock = normalizeGuardianState({prefs:{careMorningTime:"49:10",careBedtimeTime:"20:30"}});
assert.equal(badClock.prefs.careMorningTime,"09:00");
assert.equal(badClock.prefs.careBedtimeTime,"20:30");
assert.equal(normalized.prefs.littleMode,true);
assert.equal(normalized.prefs.petName,"Pup");
assert.deepEqual(careChecksForToday(normalized,"2026-10-14"),{"wake:0":true,"night:3":true});
assert.deepEqual(careChecksForToday(normalized,"2026-10-15"),{});
assert.equal(normalizeGuardianState({prefs:{careStyle:"invalid"}}).prefs.careStyle,"gentle");
console.log("Guardian caretaker preferences, wording, local daily checkmarks and privacy defaults passed.");

import { awardEligibleRewards } from "../src/guardian-auto-rewards.mjs";
const gift = {id:"gift1",name:"Sticker time",mode:"progress",targetPercent:50,claimed:false};
const tasks=[{key:"one",label:"One"},{key:"two",label:"Two"}];
let award=awardEligibleRewards([gift],tasks,{one:true},"2026-10-14");
assert.equal(award.unlocked.length,1);
assert.equal(award.rewards[0].claimed,true);
assert.equal(award.rewards[0].autoAwardedAt,"2026-10-14");
assert.equal(awardEligibleRewards(award.rewards,tasks,{one:true},"2026-10-14").unlocked.length,0);
assert.equal(awardEligibleRewards([gift],tasks,{},"2026-10-14").unlocked.length,0);
assert.equal(awardEligibleRewards([gift],[],{},"2026-10-14").unlocked.length,0);
assert.equal(awardEligibleRewards([{id:"manual",mode:"effort",goal:2,count:2}],[],{},"2026-10-14").unlocked.length,1);

import { autoGuardianGifts } from "../src/guardian-auto-rewards.mjs";
const config={automaticGifts:true,giftCategories:["stickers","celebrations","trophies"]};
const first=autoGuardianGifts([],tasks,{one:true},"2026-10-14",config);
assert.equal(first.unlocked.length,2);
assert.equal(autoGuardianGifts(first.ledger,tasks,{one:true},"2026-10-14",config).unlocked.length,0);
assert.equal(autoGuardianGifts(first.ledger,tasks,{one:true,two:true},"2026-10-14",config).unlocked.length,1);
assert.equal(autoGuardianGifts(first.ledger,tasks,{one:true},"2026-10-15",config).unlocked.length,2);
assert.equal(autoGuardianGifts([],[],{},"2026-10-14",config).unlocked.length,0);
assert.equal(autoGuardianGifts([],tasks,{one:true},"2026-10-14",{...config,automaticGifts:false}).unlocked.length,0);
assert.equal(autoGuardianGifts([],tasks,{one:true},"2026-10-14",{...config,giftCategories:["trophies"]}).unlocked.length,0);
assert.equal(autoGuardianGifts([],tasks,{one:true},"2026-10-14",config,true).unlocked.length,0);
assert.deepEqual(normalizeGuardianState({automaticGiftLedger:["2026-10-14:25","2026-10-14:25","unsafe"]}).automaticGiftLedger,["2026-10-14:25"]);

const activities = {...config,giftCategories:[...config.giftCategories,"activities"]};
assert.equal(autoGuardianGifts([], [{key:"a"},{key:"b"},{key:"c"},{key:"d"}], {a:true,b:true,c:true}, "2026-10-14", activities).unlocked.some(g=>g.category==="activities"),true);
const babyConfig = {...config,giftCategories:["babyDays"]};
const freeDay = autoGuardianGifts([],[],{},"2026-10-17",babyConfig);
assert.equal(freeDay.unlocked.length,1);
assert.match(freeDay.unlocked[0].name,/baby day/);
assert.equal(autoGuardianGifts(freeDay.ledger,[],{},"2026-10-17",babyConfig).unlocked.length,0);
assert.equal(autoGuardianGifts([],[],{},"2026-10-18",babyConfig).unlocked.length,0);
assert.equal(autoGuardianGifts([],[],{},"2026-10-17",{...babyConfig,giftCategories:[]}).unlocked.length,0);
