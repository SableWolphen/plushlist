import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = path => fs.readFileSync(new URL(path,import.meta.url),'utf8');
const load = async path => import('data:text/javascript;base64,'+Buffer.from(read(path)).toString('base64'));
const {normalizeCozyProfile,cozyCardSnapshot,supportPreferenceSummary}=await load('../src/cozy-profile.js');
const {widgetSnapshot}=await load('../src/widget-model.js');
const profile=normalizeCozyProfile({fields:{comfort_item:'Blanket',please_dont:'No surprise calls',signals:'I go quiet',unknown:'Hidden'},essentials:['one','one','two','three','four'],memories:[{id:'win',text:'I started',date:'2026-09-30'},{id:'private',text:'Private thought'}],feedback:[{note_id:'n',value:'space'}]});
assert.deepEqual(profile.essentials,['one','two','three']);
const card=cozyCardSnapshot(profile,['comfort_item','unknown','feedback'],['win']);
assert.deepEqual(card.fields,{comfort_item:'Blanket'});
assert.deepEqual(card.memories.map(m=>m.id),['win']);
assert.ok(!JSON.stringify(card).includes('Private thought'));
assert.ok(!JSON.stringify(card).includes('No surprise calls'));
assert.ok(!JSON.stringify(card).includes('feedback'));
assert.deepEqual(cozyCardSnapshot(profile,[],[]),{fields:{},memories:[]});
assert.equal(normalizeCozyProfile({fields:{helps:'x'.repeat(900)}}).fields.helps.length,500);
assert.deepEqual(normalizeCozyProfile(null),normalizeCozyProfile());
assert.match(supportPreferenceSummary(profile),/few more notes/);
const rows=[{key:'done',label:'Already done'},{key:'extra',label:'Extra',isBonus:true},{key:'care',label:'Water'},{key:'next',label:'Shower'}];
const snapshot=widgetSnapshot({rows,viewDone:{done:true},progress:33,weeklyProgress:46,theme:'baby-night'});
assert.deepEqual(snapshot.tasks.map(t=>t.key),['care','next','extra']);
assert.equal(snapshot.weeklyProgress,46);assert.equal(snapshot.progress,33);assert.equal(snapshot.theme,'baby-night');
assert.equal(snapshot.nextTask,'Water');assert.equal(snapshot.tasks[0].key,'care');
assert.deepEqual(widgetSnapshot({rows,dayType:'rest'}).tasks,[]);
assert.equal(widgetSnapshot({progress:200,weeklyProgress:-2}).progress,100);
assert.equal(widgetSnapshot({progress:200,weeklyProgress:-2}).weeklyProgress,0);
assert.match(widgetSnapshot({rows:[]}).nextTask,/Open PlushLife/);
assert.match(widgetSnapshot({rows:rows.filter(r=>!r.isBonus),viewDone:{done:true,care:true,next:true}}).nextTask,/complete/);
console.log('Cozy privacy snapshots, profile validation, memory selection, support summaries, and widget task/progress tests passed.');
