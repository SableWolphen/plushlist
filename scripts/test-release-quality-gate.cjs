"use strict";
const assert=require("node:assert/strict");
const {JOURNEYS,validateCatalog,summarize,markdown,runAll}=require("./release-quality-gate.cjs");
assert.equal(JOURNEYS.length,7);
assert.ok(validateCatalog()>=18);
assert.throws(()=>validateCatalog([{id:"x",checks:["../test-secrets.js"]}],()=>true),/unsafe/);
assert.throws(()=>validateCatalog([{id:"x",checks:["test-missing-file.cjs"]}],()=>false),/Missing/);
assert.throws(()=>validateCatalog([{id:"x",checks:["test-okay.js"]},{id:"x",checks:["test-okay.js"]}],()=>true),/duplicate/);
let calls=0;
const clean=runAll({exec:()=>{calls++;return {status:0,stdout:"",stderr:""};}});
assert.equal(clean.passed,true);
assert.equal(clean.conclusion,"automated_code_checks_passed_external_verification_required");
assert.equal(calls,JOURNEYS.reduce((n,j)=>n+j.checks.length,0));
assert.equal(clean.requiredExternalEvidence.googlePlayProductionRelease,"not_verified");
assert.equal(clean.requiredExternalEvidence.androidPhysicalDevice,"not_verified");
assert.match(markdown(clean),/external_verification_required/);
assert.match(markdown(clean),/PASS/);
const bad=runAll({exec:()=>({status:1,stderr:"intentional failure"})});
assert.equal(bad.passed,false);
assert.equal(bad.failingJourneys.length,7);
assert.equal(bad.conclusion,"code_checks_failed");
assert.match(markdown(bad),/FAIL/);
assert.equal(summarize([]).passed,false,"Empty checks cannot be reported as passing");
console.log("Release quality gate catalog, pass/fail logic, and external evidence boundaries passed");
