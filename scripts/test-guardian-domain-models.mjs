import assert from "node:assert/strict";
import {evaluateBehavior,updateNotebook,recurringDueDates,canEditMood} from "../src/guardian-domain-models.mjs";
const agreement={id:"a",status:"accepted",mode:"accountability",evaluator_user_id:"guardian"};
const link={active:true,accepted_at:"2026-01-01"};
const event={id:"e",agreement_id:"a",score:1};
const args={event,evaluatorId:"guardian",actorId:"guardian",agreement,link,score:2,reason:"Agreed review",at:"2026-11-07T12:00:00Z"};
assert.equal(evaluateBehavior(args).previous_score,1);
assert.throws(()=>evaluateBehavior({...args,actorId:"owner"}));
assert.throws(()=>evaluateBehavior({...args,link:{...link,active:false}}));
assert.throws(()=>evaluateBehavior({...args,agreement:{...agreement,status:"revoked"}}));
assert.throws(()=>evaluateBehavior({...args,event:{...event,agreement_id:"other"}}));
assert.throws(()=>evaluateBehavior({...args,score:999}));
const notebook={id:"n",version:2,content:"old"};
const edit=updateNotebook({notebook,expectedVersion:2,editorId:"owner",content:"new",at:"2026-11-07T12:00:00Z"});
assert.equal(edit.next.version,3);
assert.equal(edit.revision.previous_content,"old");
assert.equal(notebook.content,"old");
assert.throws(()=>updateNotebook({notebook,expectedVersion:1,editorId:"owner",content:"oops",at:"2026-11-07T12:00:00Z"}));
assert.throws(()=>updateNotebook({notebook:{...notebook,kind:"accepted_agreement"},expectedVersion:2,editorId:"owner",content:"oops",at:"2026-11-07T12:00:00Z"}));
assert.deepEqual(recurringDueDates({startDate:"2026-01-31",frequency:"monthly",count:3}),["2026-01-31","2026-02-28","2026-03-31"]);
assert.deepEqual(recurringDueDates({startDate:"2026-11-07",frequency:"weekly",count:2}),["2026-11-07","2026-11-14"]);
assert.throws(()=>recurringDueDates({startDate:"2026-02-30",frequency:"daily"}));
assert.equal(canEditMood({entry:{author_user_id:"owner",agreement_id:"a"},actorId:"owner",agreement,link}),true);
assert.equal(canEditMood({entry:{author_user_id:"owner",agreement_id:"a"},actorId:"guardian",agreement,link}),false);
assert.equal(canEditMood({entry:{author_user_id:"owner",agreement_id:"a"},actorId:"owner",agreement,link:{...link,active:false}}),false);
console.log("Guardian domain models: consent, scoring, notebook conflicts, recurrence, mood ownership passed.");
