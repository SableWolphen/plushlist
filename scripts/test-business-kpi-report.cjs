"use strict";
const assert=require("node:assert/strict");
const {computeReport}=require("./business-kpi-report.cjs");
const base={period:"2026-11",source:"Play aggregate report",paidAccounts:3500,signups:100,firstTaskIn24h:60,d7Eligible:80,d7Retained:32,recognizedRevenueCents:1808000,refundsCents:0,storeFeesCents:271200,variableCostsCents:122500,fixedCostsCents:150000,marketingCents:250000};
const report=computeReport(base);
assert.equal(report.activationRate,0.6);
assert.equal(report.d7RetentionRate,0.4);
assert.equal(report.operatingProfitCents,1014300);
assert.equal(report.targetReached,true);
assert.equal(report.incompleteCostFields.length,0);
const missing=computeReport({...base,storeFeesCents:undefined});
assert.equal(missing.operatingProfitCents,null);
assert.equal(missing.targetReached,null);
assert.deepEqual(missing.incompleteCostFields,["storeFeesCents"]);
assert.equal(computeReport({...base,signups:0,firstTaskIn24h:0}).activationRate,null);
assert.throws(()=>computeReport({...base,email:"someone@example.com"}),/Unsupported field/);
assert.throws(()=>computeReport({...base,period:"2026-13"}),/period/);
assert.throws(()=>computeReport({...base,source:"<script>"}),/source/);
assert.throws(()=>computeReport({...base,d7Retained:90}),/exceeds eligible/);
assert.throws(()=>computeReport({...base,recognizedRevenueCents:-1}),/nonnegative integer/);
assert.throws(()=>computeReport({...base,signups:5}),/exceeds signups/);
console.log("Verified aggregate financial reporting tests passed");
