import assert from 'node:assert/strict';
import fs from 'node:fs';
const {privateSave}=await import('data:text/javascript;base64,'+Buffer.from(fs.readFileSync('src/private-save.js','utf8')).toString('base64'));
const entries=new Map();
const storage={getItem:k=>entries.get(k),setItem:(k,v)=>entries.set(k,v),removeItem:k=>entries.delete(k)};
let offline=true,writes=[],release;
const client={from:table=>({upsert:async(row)=>{writes.push({table,row});if(release)await new Promise(r=>release=r);return {error:offline?new Error('offline'):null};}})};
const options={storage,key:'cozy-owner',client,table:'cozy_profiles',userId:'owner'};
let writer=privateSave(options);
assert.deepEqual(await writer.write({comfort:'Blanket'},{profile:{comfort:'Blanket'}}),{saved:true,synced:false});
assert.equal(writer.hasPending(),true);
writer.dispose();
writer=privateSave(options);
assert.equal(writer.read().comfort,'Blanket','Offline edits survive closing/reopening');
assert.equal(privateSave({...options,key:'cozy-other',userId:'other'}).read(),null,'Accounts cannot load each other’s edits');
offline=false;
assert.equal(await writer.flush(),true);
assert.equal(writer.hasPending(),false);
assert.equal(writes.at(-1).row.user_id,'owner');
assert.equal(entries.has('cozy-owner-pending'),false);
assert.equal(writer.read().comfort,'Blanket');
// A second edit during a request must remain queued and be sent last.
let resolveFirst;
const rows=[];
const slow={from:()=>({upsert:async row=>{rows.push(row);if(rows.length===1)await new Promise(r=>resolveFirst=r);return {error:null};}})};
const serial=privateSave({...options,client:slow,key:'wardrobe-owner',table:'user_achievements'});
const first=serial.write({selectedId:'bow'},{selected_mascot:'bow'});
await new Promise(r=>setImmediate(r));
const second=serial.write({selectedId:'cape'},{selected_mascot:'cape'});
resolveFirst();await Promise.all([first,second]);
assert.deepEqual(rows.map(r=>r.selected_mascot),['bow','cape']);
assert.equal(serial.read().selectedId,'cape');
serial.dispose();
assert.equal((await serial.write({selectedId:'bow'},{})).saved,false,'Disposed account cannot enqueue writes');
const blocked={getItem:()=>null,setItem:()=>{throw Error('full')},removeItem:()=>{}};
offline=true;
assert.equal((await privateSave({...options,storage:blocked,key:'blocked'}).write({comfort:'Rain'},{})).saved,false,'Never claim a durable save if disk and cloud both fail');
console.log('Private saves passed: offline reload, account isolation, retry, newest edit wins, sign-out, and storage failure.');
