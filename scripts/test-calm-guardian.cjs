const assert=require("node:assert/strict");
const fs=require("node:fs"),os=require("node:os"),path=require("node:path");
const React=require("react"),{create,act}=require("react-test-renderer");
global.React=React;
global.window={PlushLifeThemeCopy:require("../assets/plush-theme-copy.js")};
const temp=fs.mkdtempSync(path.join(os.tmpdir(),"calm-guardian-"));
require("esbuild").buildSync({entryPoints:["src/components/whats-changed.jsx","src/components/guardian-space-header.jsx","src/hooks/use-inline-page-focus.js"],bundle:true,format:"cjs",platform:"node",outdir:temp,outbase:"src"});
const {WhatsChanged}=require(path.join(temp,"components/whats-changed.js"));
const {GuardianSpaceHeader}=require(path.join(temp,"components/guardian-space-header.js"));
const {useInlinePageFocus}=require(path.join(temp,"hooks/use-inline-page-focus.js"));
const label=n=>n.children.filter(c=>typeof c==="string").join("");
const button=(tree,text)=>tree.root.findAllByType("button").find(n=>label(n)===text);
(async()=>{
  let reads=0,closed=0,tree;
  await act(async()=>{tree=create(React.createElement(WhatsChanged,{unread:true,onMarkRead:async()=>{reads++;return true;},onClose:()=>closed++}));});
  assert.equal(reads,0,"opening release notes never marks them read automatically");
  assert.equal(tree.root.findAllByProps({role:"dialog"}).length,0,"updates are a page, not a modal");
  assert(button(tree,"Mark as read"));
  await act(async()=>button(tree,"Mark as read").props.onClick());
  assert.equal(reads,1);assert(JSON.stringify(tree.toJSON()).includes("All caught up"));
  await act(async()=>button(tree,"Back").props.onClick());assert.equal(closed,1);
  await act(async()=>tree.update(React.createElement(WhatsChanged,{unread:true,onMarkRead:async()=>false,onClose:()=>{}})));
  await act(async()=>button(tree,"Mark as read").props.onClick());
  assert(JSON.stringify(tree.toJSON()).includes("Could not confirm"),"failed persistence is visible");
  await act(async()=>tree.unmount());
  const routes=[];
  await act(async()=>{tree=create(React.createElement(GuardianSpaceHeader,{area:"home",relationshipLabel:"You & Alex",onSelect:p=>routes.push(p),onSupport:()=>routes.push("support"),onRewards:()=>routes.push("rewards")}));});
  const nav=tree.root.findByProps({"aria-label":"Guardian sections"});
  assert.equal(nav.findAllByType("button").length,5);
  assert.equal(nav.findAllByType("button").filter(b=>b.props["aria-pressed"]).length,1);
  await act(async()=>button(tree,"Check-ins").props.onClick());
  await act(async()=>button(tree,"Sharing & permissions").props.onClick());
  await act(async()=>button(tree,"Ask for a little support").props.onClick());
  assert.deepEqual(routes,["checkins","overview","support"],"navigation is explicit and keeps permissions separate");
  assert.equal(tree.root.findAllByProps({role:"dialog"}).length,0);
  await act(async()=>tree.unmount());
  let frame, focused=0, restored=0, closes=0, dialogOpen=false, historyBack=0;
  const doc=new EventTarget();
  doc.activeElement={isConnected:true,closest:()=>null,focus:()=>restored++};
  doc.querySelectorAll=()=>[{getClientRects:()=>dialogOpen?[{}]:[]}];
  doc.querySelector=selector=>selector.includes('role="dialog"') ? (dialogOpen?{}:null) : {setAttribute(){},focus:()=>focused++,scrollIntoView(){}};
  global.document=doc;window.requestAnimationFrame=fn=>{frame=fn;return 1;};window.cancelAnimationFrame=()=>{};
  function Probe({page}){useInlinePageFocus(page,()=>closes++);return null;}
  await act(async()=>{tree=create(React.createElement(Probe,{page:"updates"}));});
  frame();assert.equal(focused,1,"opening a utility moves keyboard focus into the page");
  const native=fs.readFileSync("src/native-bridge.js","utf8");
  const handler=native.match(/Plugins\.App\.addListener\("backButton", function \(state\) \{([\s\S]*?)\n    \}\);/)[1];
  const back=require("node:vm").runInNewContext('(function(state){'+handler+'})',{countOverlays:()=>0,document:doc,Event,window:{history:{back:()=>historyBack++}},exitArmed:false,armExit:()=>{throw Error("must not exit while an in-page utility is open");}});
  back({canGoBack:true});assert.equal(closes,1);assert.equal(historyBack,0,"Android Back closes the utility before leaving the app");
  dialogOpen=true;const blocked=new Event("plushlife:back-request",{cancelable:true});doc.dispatchEvent(blocked);assert.equal(closes,1,"a destructive dialog keeps precedence");dialogOpen=false;
  await act(async()=>tree.update(React.createElement(Probe,{page:null})));assert.equal(restored,1,"closing restores the opener's focus");
  back({canGoBack:true});assert.equal(historyBack,1,"ordinary Android navigation works after the utility closes");
  await act(async()=>tree.unmount());delete global.document;
  const app=fs.readFileSync("src/app-source.jsx","utf8");
  assert(!app.includes('return "changelog"'),"unread updates never enter the automatic prompt queue");
  assert(!app.includes('setTimeout(() => setCheckInPopupOpen(true)'),"sign-in cannot auto-open check-in");
  assert(!app.includes('setDailyJournalPromptOpen(true)'),"evening cannot auto-open journal");
  const inline=app.match(/<div role="region" className="pl-calm-inline-page"[^>]+checkin-popup-title[^>]*>/);
  assert(inline,"manual daily check-in uses an in-page region");
  const css=fs.readFileSync("assets/calm-guardian.css","utf8");
  assert(css.includes("@media(max-width:700px)")&&css.includes("grid-template-columns:1fr"));
  console.log("Calm Guardian: explicit navigation, unread persistence/failure, non-modal updates and intentional care entry passed.");
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>fs.rmSync(temp,{recursive:true,force:true}));
