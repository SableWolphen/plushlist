import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { MAIN_DESTINATIONS, mainDestination } from "../src/navigation.mjs";
const get = name => readFileSync(new URL("../"+name, import.meta.url),"utf8");
const guardian = MAIN_DESTINATIONS.filter(item => item.id === "guardian");
assert.equal(guardian.length,0,"Guardian lives inside Care rather than as its own bottom tab");
assert.equal(mainDestination("guardian"),"care","Care stays selected while Guardian is open");
assert.match(get("src/components/care-panel.jsx"),/Your trusted person[\s\S]*props\.onOpenSupport\?\.\(\)/,"Care's trusted person card opens Guardian");
assert.match(get("src/app-source.jsx"),/className="pl3-back-to-care"/,"Guardian offers a way back to Care");
const app=get("src/app-source.jsx");
assert.match(app,/MAIN_DESTINATIONS\.map\(\(\{id, label, icon\}\)/,"Bottom nav must render each destination");
assert.match(app,/dashboard === "guardian"/,"Guardian destination must open the actual panel");
const screen=get("src/components/guardian-panel.jsx")+get("src/components/guardian-space-header.jsx");
for(const area of ["support","together","overview"]) assert.match(screen,new RegExp('(?:setGuardianArea|onSelect)\\("'+area+'"\\)'),"Guardian home routes to "+area);
assert.match(screen,/supportViewMode === "caretaker"/,"Guardian home must distinguish Guardian and Cozy roles");
assert.match(screen,/canSendSupportNotes/);
assert.match(screen,/canAddSupportRewards/);
assert.match(screen,/updateCaretakerPermission/);
assert.match(screen,/setSupportAction\("note"\); setGuardianArea\("support"\)/,"Care shortcut opens notes");
assert.match(screen,/setSupportAction\(canAddSupportRewards \? "reward" : "task"\)/,"Reward shortcut honors Guardian capabilities");
console.log("Guardian 2.0 navigation, role-aware home and permission preservation guards passed.");
